import { useState, useRef } from "react";
import { supabase } from "@/integrations/supabase/client";
import { RiskReport } from "@/hooks/useReports";
import { useLanguage } from "@/hooks/useLanguage";
import { useAuth } from "@/hooks/useAuth";
import { useProjects } from "@/hooks/useProjects";
import { useToast } from "@/hooks/use-toast";
import { Button } from "@/components/ui/button";
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { FileText, Loader2, Save, Download } from "lucide-react";

interface ReportGeneratorProps {
  reports: RiskReport[];
}

interface ReportData {
  summary: string;
  risk_analysis: string;
  trends: string;
  improvements: string;
  action_plan: string;
  conclusion: string;
}

type ReportType = "monthly" | "quarterly" | "yearly";

function ProseReportView({ report, projectName, periodLabel, lang }: {
  report: ReportData;
  projectName: string;
  periodLabel: string;
  lang: string;
}) {
  const sectionTitle = (sv: string, en: string) => lang === "en" ? en : sv;

  return (
    <div className="prose-report space-y-6">
      <div className="text-center border-b border-border pb-4 mb-6">
        <h2 className="text-lg font-bold text-card-foreground">{projectName}</h2>
        <p className="text-sm text-muted-foreground">{periodLabel}</p>
      </div>

      {[
        { key: "summary", sv: "Sammanfattning", en: "Executive Summary" },
        { key: "risk_analysis", sv: "Riskanalys", en: "Risk Analysis" },
        { key: "trends", sv: "Trender och mönster", en: "Trends and Patterns" },
        { key: "improvements", sv: "Positiva resultat", en: "Positive Results" },
        { key: "action_plan", sv: "Åtgärdsplan", en: "Action Plan" },
        { key: "conclusion", sv: "Slutsats", en: "Conclusion" },
      ].map(s => {
        const text = (report as any)[s.key];
        if (!text) return null;
        return (
          <section key={s.key}>
            <h3 className="text-sm font-bold text-card-foreground mb-3 border-b border-border pb-2 uppercase tracking-wide">
              {sectionTitle(s.sv, s.en)}
            </h3>
            <div className="text-sm text-card-foreground/80 leading-relaxed">
              {text.split("\n").filter(Boolean).map((p: string, i: number) => (
                <p key={i} className="mb-3">{p}</p>
              ))}
            </div>
          </section>
        );
      })}
    </div>
  );
}

function downloadPDF(report: ReportData, projectName: string, periodLabel: string, lang: string) {
  const sectionTitle = (sv: string, en: string) => lang === "en" ? en : sv;
  const title = `${projectName} — ${periodLabel}`;

  const html = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>${title}</title>
  <style>
    @page { margin: 2.5cm; size: A4; }
    body { font-family: 'Georgia', 'Times New Roman', serif; font-size: 11pt; line-height: 1.6; color: #1a1a1a; max-width: 100%; }
    h1 { font-size: 18pt; text-align: center; margin-bottom: 4pt; font-weight: 700; }
    .subtitle { text-align: center; font-size: 11pt; color: #555; margin-bottom: 24pt; border-bottom: 1px solid #ccc; padding-bottom: 16pt; }
    h2 { font-size: 13pt; font-weight: 700; margin-top: 24pt; margin-bottom: 8pt; color: #222; border-bottom: 1px solid #e0e0e0; padding-bottom: 4pt; }
    p { margin: 0 0 10pt 0; text-align: justify; }
    .footer { margin-top: 32pt; padding-top: 12pt; border-top: 1px solid #ccc; font-size: 9pt; color: #888; text-align: center; }
  </style>
</head>
<body>
  <h1>${projectName}</h1>
  <div class="subtitle">${periodLabel}</div>

  <h2>${sectionTitle("Sammanfattning", "Executive Summary")}</h2>
  ${report.summary.split("\n").filter(Boolean).map(p => `<p>${p}</p>`).join("")}

  <h2>${sectionTitle("Riskanalys", "Risk Analysis")}</h2>
  ${report.risk_analysis.split("\n").filter(Boolean).map(p => `<p>${p}</p>`).join("")}

  <h2>${sectionTitle("Trender och mönster", "Trends and Patterns")}</h2>
  ${report.trends.split("\n").filter(Boolean).map(p => `<p>${p}</p>`).join("")}

  <h2>${sectionTitle("Positiva resultat", "Positive Results")}</h2>
  ${report.improvements.split("\n").filter(Boolean).map(p => `<p>${p}</p>`).join("")}

  <h2>${sectionTitle("Åtgärdsplan", "Action Plan")}</h2>
  ${report.action_plan.split("\n").filter(Boolean).map(p => `<p>${p}</p>`).join("")}

  <h2>${sectionTitle("Slutsats", "Conclusion")}</h2>
  ${report.conclusion.split("\n").filter(Boolean).map(p => `<p>${p}</p>`).join("")}

  <div class="footer">${sectionTitle("Genererad av RiskRadar", "Generated by RiskRadar")} — ${new Date().toLocaleDateString(lang === "en" ? "en-US" : "sv-SE")}</div>
</body>
</html>`;

  const printWindow = window.open("", "_blank");
  if (!printWindow) return;
  printWindow.document.write(html);
  printWindow.document.close();
  setTimeout(() => { printWindow.print(); }, 500);
}

export default function ReportGenerator({ reports }: ReportGeneratorProps) {
  const { lang, t } = useLanguage();
  const { activeProjectId, user } = useAuth();
  const { projects } = useProjects();
  const { toast } = useToast();
  const [open, setOpen] = useState(false);
  const [loading, setLoading] = useState(false);
  const [saving, setSaving] = useState(false);
  const [report, setReport] = useState<ReportData | null>(null);
  const [reportType, setReportType] = useState<ReportType>("monthly");
  const [selectedPeriod, setSelectedPeriod] = useState(() => {
    const now = new Date();
    return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}`;
  });

  const projectName = projects.find(p => p.id === activeProjectId)?.name ?? t("project.allProjects");

  const getPeriodLabel = (period: string, type: ReportType) => {
    const [year, month] = period.split("-").map(Number);
    if (type === "yearly") return `${year}`;
    if (type === "quarterly") {
      const q = Math.ceil(month / 3);
      return `Q${q} ${year}`;
    }
    const date = new Date(year, month - 1);
    return date.toLocaleDateString(lang === "en" ? "en-US" : "sv-SE", { year: "numeric", month: "long" });
  };

  const getFilteredReports = () => {
    const [year, month] = selectedPeriod.split("-").map(Number);
    let startDate: Date, endDate: Date;

    if (reportType === "yearly") {
      startDate = new Date(year, 0, 1);
      endDate = new Date(year, 11, 31, 23, 59, 59);
    } else if (reportType === "quarterly") {
      const q = Math.ceil(month / 3);
      startDate = new Date(year, (q - 1) * 3, 1);
      endDate = new Date(year, q * 3, 0, 23, 59, 59);
    } else {
      startDate = new Date(year, month - 1, 1);
      endDate = new Date(year, month, 0, 23, 59, 59);
    }

    return reports.filter(r => {
      const d = new Date(r.created_at);
      return d >= startDate && d <= endDate;
    });
  };

  const generateReport = async () => {
    setLoading(true);
    setReport(null);

    const periodReports = getFilteredReports();
    const periodLabel = getPeriodLabel(selectedPeriod, reportType);

    try {
      const { data, error } = await supabase.functions.invoke("generate-report", {
        body: {
          reports: periodReports.map(r => ({
            title: r.title,
            description: r.description,
            category: r.category,
            risk_level: r.risk_level,
            status: r.status,
            report_type: r.report_type,
            building: r.building,
            specific_location: r.specific_location,
            body_part: r.body_part,
            injury_type: r.injury_type,
            ai_explanation: r.ai_explanation,
          })),
          project_name: projectName,
          period_label: periodLabel,
          report_type: reportType,
          language: lang,
        },
      });

      if (error) throw error;
      setReport(data);
    } catch (e) {
      console.error("Report generation error:", e);
      toast({ title: t("reportGen.error"), variant: "destructive" });
    }
    setLoading(false);
  };

  const saveDocument = async () => {
    if (!report || !user) return;
    setSaving(true);

    const periodLabel = getPeriodLabel(selectedPeriod, reportType);
    const title = `${t(`reportGen.${reportType}`)} — ${projectName} — ${periodLabel}`;

    const { error } = await supabase.from("documents").insert({
      title,
      document_type: reportType,
      period_label: periodLabel,
      project_id: activeProjectId,
      project_name: projectName,
      content: report as any,
      language: lang,
      created_by: user.id,
    });

    if (error) {
      toast({ title: t("reportGen.saveError"), variant: "destructive" });
    } else {
      toast({ title: t("reportGen.saved") });
    }
    setSaving(false);
  };

  const periodOptions = reportType === "yearly"
    ? Array.from({ length: 5 }, (_, i) => {
        const y = new Date().getFullYear() - i;
        return { value: `${y}-01`, label: `${y}` };
      })
    : reportType === "quarterly"
    ? Array.from({ length: 8 }, (_, i) => {
        const d = new Date();
        d.setMonth(d.getMonth() - i * 3);
        const q = Math.ceil((d.getMonth() + 1) / 3);
        const val = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;
        return { value: val, label: `Q${q} ${d.getFullYear()}` };
      })
    : Array.from({ length: 12 }, (_, i) => {
        const d = new Date();
        d.setMonth(d.getMonth() - i);
        const val = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;
        return { value: val, label: getPeriodLabel(val, "monthly") };
      });

  const periodLabel = getPeriodLabel(selectedPeriod, reportType);

  return (
    <>
      <Button variant="outline" size="sm" onClick={() => setOpen(true)} className="text-xs">
        <FileText className="h-4 w-4 mr-1.5" />
        {t("reportGen.button")}
      </Button>

      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent className="max-w-2xl max-h-[90vh] overflow-y-auto">
          <DialogHeader>
            <DialogTitle className="flex items-center gap-2">
              <FileText className="h-5 w-5 text-accent" />
              {t("reportGen.title")}
            </DialogTitle>
          </DialogHeader>

          <div className="flex items-center gap-2 mb-4 flex-wrap">
            <div className="flex gap-1">
              {(["monthly", "quarterly", "yearly"] as ReportType[]).map(type => (
                <button
                  key={type}
                  onClick={() => { setReportType(type); setReport(null); }}
                  className={`text-xs font-medium px-3 py-1.5 rounded-full border transition-colors ${
                    reportType === type
                      ? "bg-primary text-primary-foreground border-primary"
                      : "bg-card text-muted-foreground border-border hover:border-accent"
                  }`}
                >
                  {t(`reportGen.${type}`)}
                </button>
              ))}
            </div>

            <select
              value={selectedPeriod}
              onChange={(e) => { setSelectedPeriod(e.target.value); setReport(null); }}
              className="flex h-9 rounded-md border border-input bg-background px-3 py-1 text-sm"
            >
              {periodOptions.map(o => (
                <option key={o.value} value={o.value}>{o.label}</option>
              ))}
            </select>

            <Button onClick={generateReport} disabled={loading} className="bg-accent text-accent-foreground hover:bg-accent/90">
              {loading ? (
                <span className="flex items-center gap-2">
                  <Loader2 className="h-4 w-4 animate-spin" />
                  {t("reportGen.generating")}
                </span>
              ) : (
                t("reportGen.generate")
              )}
            </Button>
          </div>

          {report && (
            <div className="animate-fade-in">
              <div className="flex justify-end gap-2 mb-4">
                <Button onClick={() => downloadPDF(report, projectName, periodLabel, lang)} variant="outline" size="sm">
                  <Download className="h-4 w-4 mr-1.5" />
                  {t("reportGen.downloadPdf")}
                </Button>
                <Button onClick={saveDocument} disabled={saving} variant="outline" size="sm">
                  <Save className="h-4 w-4 mr-1.5" />
                  {saving ? t("common.loading") : t("reportGen.saveDoc")}
                </Button>
              </div>

              <ProseReportView report={report} projectName={projectName} periodLabel={periodLabel} lang={lang} />
            </div>
          )}
        </DialogContent>
      </Dialog>
    </>
  );
}
