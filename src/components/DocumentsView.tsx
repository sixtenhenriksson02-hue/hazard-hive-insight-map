import { useState, useEffect } from "react";
import { supabase } from "@/integrations/supabase/client";
import { useAuth } from "@/hooks/useAuth";
import { useLanguage } from "@/hooks/useLanguage";
import { Button } from "@/components/ui/button";
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { FileText, Trash2, Eye, Calendar, Download } from "lucide-react";

interface DocumentRecord {
  id: string;
  title: string;
  document_type: string;
  period_label: string;
  project_name: string | null;
  content: any;
  language: string;
  created_at: string;
}

function downloadDocPDF(content: any, title: string, lang: string) {
  const sectionTitle = (sv: string, en: string) => lang === "en" ? en : sv;
  const isProseFormat = typeof content.risk_analysis === "string";

  let bodyHtml = "";

  if (isProseFormat) {
    const sections = [
      { key: "summary", sv: "Sammanfattning", en: "Executive Summary" },
      { key: "risk_analysis", sv: "Riskanalys", en: "Risk Analysis" },
      { key: "trends", sv: "Trender och mönster", en: "Trends and Patterns" },
      { key: "improvements", sv: "Positiva resultat", en: "Positive Results" },
      { key: "action_plan", sv: "Åtgärdsplan", en: "Action Plan" },
      { key: "conclusion", sv: "Slutsats", en: "Conclusion" },
    ];
    for (const s of sections) {
      const text = content[s.key];
      if (text) {
        bodyHtml += `<h2>${sectionTitle(s.sv, s.en)}</h2>`;
        bodyHtml += text.split("\n").filter(Boolean).map((p: string) => `<p>${p}</p>`).join("");
      }
    }
  } else {
    // Legacy format
    if (content.summary) bodyHtml += `<h2>${sectionTitle("Sammanfattning", "Summary")}</h2><p>${content.summary}</p>`;
    if (content.key_risks?.length) {
      bodyHtml += `<h2>${sectionTitle("Nyckelrisker", "Key Risks")}</h2>`;
      content.key_risks.forEach((r: any) => { bodyHtml += `<p><strong>${r.risk}</strong> (${r.severity}, ${r.count} st) — ${r.recommendation}</p>`; });
    }
    if (content.trends?.length) {
      bodyHtml += `<h2>${sectionTitle("Trender", "Trends")}</h2>`;
      content.trends.forEach((t: string) => { bodyHtml += `<p>${t}</p>`; });
    }
    if (content.improvements?.length) {
      bodyHtml += `<h2>${sectionTitle("Förbättringar", "Improvements")}</h2>`;
      content.improvements.forEach((i: string) => { bodyHtml += `<p>${i}</p>`; });
    }
    if (content.action_plan?.length) {
      bodyHtml += `<h2>${sectionTitle("Åtgärdsplan", "Action Plan")}</h2>`;
      content.action_plan.forEach((a: any) => { bodyHtml += `<p>${a.action} — ${a.priority} — ${a.responsible}</p>`; });
    }
  }

  const html = `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <title>${title}</title>
  <style>
    @page { margin: 2.5cm; size: A4; }
    body { font-family: 'Georgia', 'Times New Roman', serif; font-size: 11pt; line-height: 1.6; color: #1a1a1a; }
    h1 { font-size: 18pt; text-align: center; margin-bottom: 16pt; font-weight: 700; border-bottom: 1px solid #ccc; padding-bottom: 12pt; }
    h2 { font-size: 13pt; font-weight: 700; margin-top: 24pt; margin-bottom: 8pt; color: #222; border-bottom: 1px solid #e0e0e0; padding-bottom: 4pt; }
    p { margin: 0 0 10pt 0; text-align: justify; }
    .footer { margin-top: 32pt; padding-top: 12pt; border-top: 1px solid #ccc; font-size: 9pt; color: #888; text-align: center; }
  </style>
</head>
<body>
  <h1>${title}</h1>
  ${bodyHtml}
  <div class="footer">${sectionTitle("Genererad av RiskRadar", "Generated by RiskRadar")} — ${new Date().toLocaleDateString(lang === "en" ? "en-US" : "sv-SE")}</div>
</body>
</html>`;

  const printWindow = window.open("", "_blank");
  if (!printWindow) return;
  printWindow.document.write(html);
  printWindow.document.close();
  setTimeout(() => { printWindow.print(); }, 500);
}

export default function DocumentsView() {
  const { viewAs } = useAuth();
  const { t, lang } = useLanguage();
  const isAdmin = viewAs === "admin";
  const [docs, setDocs] = useState<DocumentRecord[]>([]);
  const [loading, setLoading] = useState(true);
  const [selectedDoc, setSelectedDoc] = useState<DocumentRecord | null>(null);
  const [filter, setFilter] = useState<string>("all");

  const fetchDocs = async () => {
    const { data, error } = await supabase
      .from("documents")
      .select("*")
      .order("created_at", { ascending: false });
    if (!error && data) setDocs(data as DocumentRecord[]);
    setLoading(false);
  };

  useEffect(() => { fetchDocs(); }, []);

  const deleteDoc = async (id: string) => {
    await supabase.from("documents").delete().eq("id", id);
    setDocs(prev => prev.filter(d => d.id !== id));
  };

  const filteredDocs = filter === "all" ? docs : docs.filter(d => d.document_type === filter);

  const typeLabel: Record<string, string> = {
    monthly: t("reportGen.monthly"),
    quarterly: t("reportGen.quarterly"),
    yearly: t("reportGen.yearly"),
  };

  const sectionTitle = (sv: string, en: string) => lang === "en" ? en : sv;

  const renderDocContent = (content: any) => {
    const isProseFormat = typeof content.risk_analysis === "string";

    if (isProseFormat) {
      const sections = [
        { key: "summary", sv: "Sammanfattning", en: "Executive Summary" },
        { key: "risk_analysis", sv: "Riskanalys", en: "Risk Analysis" },
        { key: "trends", sv: "Trender och mönster", en: "Trends and Patterns" },
        { key: "improvements", sv: "Positiva resultat", en: "Positive Results" },
        { key: "action_plan", sv: "Åtgärdsplan", en: "Action Plan" },
        { key: "conclusion", sv: "Slutsats", en: "Conclusion" },
      ];

      return (
        <div className="space-y-5">
          {sections.map(s => {
            const text = content[s.key];
            if (!text) return null;
            return (
              <section key={s.key}>
                <h3 className="text-sm font-bold text-card-foreground mb-2 border-b border-border pb-1">
                  {sectionTitle(s.sv, s.en)}
                </h3>
                <div className="text-sm text-muted-foreground leading-relaxed whitespace-pre-line">{text}</div>
              </section>
            );
          })}
        </div>
      );
    }

    // Legacy bullet-point format
    return (
      <div className="space-y-4">
        {content.summary && (
          <div className="rounded-lg border border-border bg-muted/30 p-4">
            <p className="text-sm text-muted-foreground">{content.summary}</p>
          </div>
        )}
        {content.key_risks?.length > 0 && (
          <div>
            <h3 className="text-sm font-bold text-card-foreground mb-2">{sectionTitle("Nyckelrisker", "Key Risks")}</h3>
            {content.key_risks.map((risk: any, i: number) => (
              <p key={i} className="text-sm text-muted-foreground mb-1">
                <strong>{risk.risk}</strong> ({risk.severity}, {risk.count} st) — {risk.recommendation}
              </p>
            ))}
          </div>
        )}
        {content.trends?.length > 0 && (
          <div>
            <h3 className="text-sm font-bold text-card-foreground mb-2">{sectionTitle("Trender", "Trends")}</h3>
            {content.trends.map((trend: string, i: number) => (
              <p key={i} className="text-sm text-muted-foreground mb-1">{trend}</p>
            ))}
          </div>
        )}
        {content.improvements?.length > 0 && (
          <div>
            <h3 className="text-sm font-bold text-card-foreground mb-2">{sectionTitle("Förbättringar", "Improvements")}</h3>
            {content.improvements.map((imp: string, i: number) => (
              <p key={i} className="text-sm text-muted-foreground mb-1">{imp}</p>
            ))}
          </div>
        )}
        {content.action_plan?.length > 0 && (
          <div>
            <h3 className="text-sm font-bold text-card-foreground mb-2">{sectionTitle("Åtgärdsplan", "Action Plan")}</h3>
            {content.action_plan.map((action: any, i: number) => (
              <p key={i} className="text-sm text-muted-foreground mb-1">{action.action} — {action.priority} — {action.responsible}</p>
            ))}
          </div>
        )}
      </div>
    );
  };

  return (
    <>
      <div className="flex gap-2 mb-4">
        {["all", "monthly", "quarterly", "yearly"].map(f => (
          <button
            key={f}
            onClick={() => setFilter(f)}
            className={`text-xs font-medium px-3 py-1.5 rounded-full border transition-colors ${
              filter === f
                ? "bg-primary text-primary-foreground border-primary"
                : "bg-card text-muted-foreground border-border hover:border-accent"
            }`}
          >
            {f === "all" ? t("common.all") : typeLabel[f]}
          </button>
        ))}
      </div>

      {loading ? (
        <p className="text-muted-foreground text-center py-12">{t("common.loading")}</p>
      ) : filteredDocs.length === 0 ? (
        <div className="text-center py-12">
          <FileText className="h-12 w-12 text-muted-foreground/30 mx-auto mb-3" />
          <p className="text-muted-foreground">{t("documents.empty")}</p>
        </div>
      ) : (
        <div className="space-y-3">
          {filteredDocs.map(doc => (
            <div key={doc.id} className="flex items-center gap-4 rounded-lg border border-border bg-card p-4">
              <FileText className="h-8 w-8 text-accent shrink-0" />
              <div className="flex-1 min-w-0">
                <h3 className="text-sm font-semibold text-card-foreground truncate">{doc.title}</h3>
                <div className="flex items-center gap-3 text-xs text-muted-foreground mt-1">
                  <span className="px-2 py-0.5 rounded-full bg-accent/10 text-accent font-medium">
                    {typeLabel[doc.document_type] ?? doc.document_type}
                  </span>
                  <span className="flex items-center gap-1">
                    <Calendar className="h-3 w-3" />
                    {new Date(doc.created_at).toLocaleDateString(lang === "en" ? "en-US" : "sv-SE")}
                  </span>
                </div>
              </div>
              <div className="flex gap-2">
                <Button variant="outline" size="sm" onClick={() => downloadDocPDF(doc.content, doc.title, doc.language)}>
                  <Download className="h-4 w-4" />
                </Button>
                <Button variant="outline" size="sm" onClick={() => setSelectedDoc(doc)}>
                  <Eye className="h-4 w-4" />
                </Button>
                {isAdmin && (
                  <Button variant="outline" size="sm" onClick={() => deleteDoc(doc.id)} className="text-destructive hover:text-destructive">
                    <Trash2 className="h-4 w-4" />
                  </Button>
                )}
              </div>
            </div>
          ))}
        </div>
      )}

      <Dialog open={!!selectedDoc} onOpenChange={(o) => !o && setSelectedDoc(null)}>
        <DialogContent className="max-w-2xl max-h-[90vh] overflow-y-auto">
          <DialogHeader>
            <DialogTitle className="flex items-center gap-2">
              <FileText className="h-5 w-5 text-accent" />
              {selectedDoc?.title}
            </DialogTitle>
          </DialogHeader>
          {selectedDoc?.content && (
            <div className="animate-fade-in">
              <div className="flex justify-end mb-4">
                <Button variant="outline" size="sm" onClick={() => downloadDocPDF(selectedDoc.content, selectedDoc.title, selectedDoc.language)}>
                  <Download className="h-4 w-4 mr-1.5" />
                  {t("reportGen.downloadPdf")}
                </Button>
              </div>
              {renderDocContent(selectedDoc.content)}
            </div>
          )}
        </DialogContent>
      </Dialog>
    </>
  );
}
